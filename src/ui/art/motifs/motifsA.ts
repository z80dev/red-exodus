type Pt = [number, number];
const rad = (deg: number) => (deg * Math.PI) / 180;
const pt = ([x, y]: Pt) => `${Math.round(x * 10) / 10} ${Math.round(y * 10) / 10}`;

/** Pointed leaf/grain from `base` along `ang` (degrees, 0 = up, clockwise): [outline, shaded right half, midrib]. */
function leaf(base: Pt, ang: number, len: number, hw: number): [string, string, string] {
  const [ux, uy, px, py] = [Math.sin(rad(ang)), -Math.cos(rad(ang)), Math.cos(rad(ang)), Math.sin(rad(ang))];
  const at = (a: number, q: number): Pt => [base[0] + ux * a + px * q, base[1] + uy * a + py * q];
  const k = hw * 1.33;
  const right = `C${pt(at(len * 0.66, k * 0.9))} ${pt(at(len * 0.12, k))} ${pt(base)}Z`;
  return [
    `M${pt(base)}C${pt(at(len * 0.12, -k))} ${pt(at(len * 0.66, -k * 0.9))} ${pt(at(len, 0))}${right}`,
    `M${pt(base)}Q${pt(at(len * 0.5, 0.6))} ${pt(at(len, 0))}${right}`,
    `M${pt(at(len * 0.12, 0))}Q${pt(at(len * 0.5, 0.5))} ${pt(at(len * 0.8, 0))}`,
  ];
}

/** Bound wheat sheaf: seven ears fanning from the tie at (50, 67), each a chain of paired grains with awns. */
function sheaf() {
  const grains: string[] = [], shade: string[] = [], glint: string[] = [], awns: string[] = [], stalks: string[] = [], butts: string[] = [];
  for (let i = 0; i < 7; i++) {
    const th = -45 + i * 15;
    const outer = Math.abs(i - 3) / 3;
    const len = 32 - outer * 7;
    const tie: Pt = [50 + (i - 3) * 1.6, 67];
    const ear: Pt = [50 + Math.sin(rad(th)) * len, 67 - Math.cos(rad(th)) * len];
    const bend: Pt = [50 + Math.sin(rad(th * 0.55)) * len * 0.55, 67 - Math.cos(rad(th * 0.55)) * len * 0.55];
    stalks.push(`M${pt(tie)}Q${pt(bend)} ${pt(ear)}`);
    butts.push(`M${pt(tie)}Q${pt([50 + (i - 3) * 1.8, 81])} ${pt([50 + (i - 3) * 3.6, 97])}`);
    const phi = th * 1.18;
    const [ux, uy, px, py] = [Math.sin(rad(phi)), -Math.cos(rad(phi)), Math.cos(rad(phi)), Math.sin(rad(phi))];
    for (let k = 0; k < 5; k++) {
      for (const side of [-1, 1]) {
        const base: Pt = [ear[0] + ux * (1 + k * 3.8) + px * side * 0.6, ear[1] + uy * (1 + k * 3.8) + py * side * 0.6];
        const ang = phi + side * 24;
        const [d, half] = leaf(base, ang, 6.4, 2.2);
        grains.push(d);
        if (side > 0) shade.push(half);
        const tip: Pt = [base[0] + Math.sin(rad(ang)) * 6.4, base[1] - Math.cos(rad(ang)) * 6.4];
        const aw = phi + side * 12;
        awns.push(`M${pt(tip)}L${pt([tip[0] + Math.sin(rad(aw)) * 7, tip[1] - Math.cos(rad(aw)) * 7])}`);
      }
    }
    const top: Pt = [ear[0] + ux * (19 - outer * 3), ear[1] + uy * (19 - outer * 3)];
    const [d, half] = leaf(top, phi, 6.4, 2.2);
    grains.push(d);
    shade.push(half);
    awns.push(`M${pt([top[0] + ux * 6.4, top[1] + uy * 6.4])}L${pt([top[0] + ux * 14.4, top[1] + uy * 14.4])}`);
    glint.push(`M${pt([ear[0] + ux * 3 - px * 1.6, ear[1] + uy * 3 - py * 1.6])}L${pt([ear[0] + ux * 13 - px * 1.6, ear[1] + uy * 13 - py * 1.6])}`);
  }
  return { grains: grains.join(''), shade: shade.join(''), glint: glint.join(''), awns: awns.join(''), stalks: stalks.join(''), butts: butts.join('') };
}
const SHEAF = sheaf();

/** Laurel wreath: two branches of paired leaves along a circle (r 37 about (50, 51)), open at the top. */
function wreath() {
  const leaves: string[] = [], shade: string[] = [], ribs: string[] = [], stems: string[] = [];
  const berries: Pt[] = [];
  for (const side of [1, -1]) {
    const at = (t: number): Pt => [50 - side * 37 * Math.sin(rad(t)), 51 + 37 * Math.cos(rad(t))];
    const add = ([d, half, rib]: [string, string, string]) => {
      leaves.push(d);
      shade.push(half);
      ribs.push(rib);
    };
    [20, 35, 50, 65, 80, 95, 110, 125, 138].forEach((t, i) => {
      const len = 15 - i * 0.55;
      add(leaf(at(t), side * (t - 130), len, len * 0.27));
      add(leaf(at(t), side * (t - 50), len * 0.86, len * 0.27));
      if (i % 3 === 1) berries.push(at(t + 6));
    });
    add(leaf(at(150), side * 60, 11, 3));
    stems.push(`M${pt(at(6))}A37 37 0 0 ${side > 0 ? 1 : 0} ${pt(at(150))}`);
  }
  return { leaves: leaves.join(''), shade: shade.join(''), ribs: ribs.join(''), stems: stems.join(''), berries };
}
